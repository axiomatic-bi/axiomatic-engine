class TestGenerateStagingSql:
    def _basic_columns(self) -> list[ColumnInfo]:
        return [
            ColumnInfo(name="Period", data_type="DATE", is_nullable=True),
            ColumnInfo(name="Commissioner Org Code", data_type="VARCHAR", is_nullable=True),
            ColumnInfo(name="0 To 1 Weeks SUM 1", data_type="INTEGER", is_nullable=True),
            ColumnInfo(name="_dlt_load_id", data_type="VARCHAR", is_nullable=False),
            ColumnInfo(name="_dlt_id", data_type="VARCHAR", is_nullable=False),
        ]

    def test_output_contains_header_comment(self) -> None:
        sql = generate_staging_sql(
            source_name="my_source",
            table_name="my_table",
            columns=self._basic_columns(),
        )
        assert "auto-generated by axiomatic-engine generate-staging" in sql

    def test_output_contains_config_block(self) -> None:
        sql = generate_staging_sql(
            source_name="my_source",
            table_name="my_table",
            columns=self._basic_columns(),
        )
        assert "{{ config(" in sql
        assert "env_var('AXIOMATIC_SCHEMA_SILVER', 'silver')" in sql

    def test_output_contains_from_source(self) -> None:
        sql = generate_staging_sql(
            source_name="my_source",
            table_name="my_table",
            columns=self._basic_columns(),
        )
        assert "from {{ source('my_source', 'my_table') }}" in sql

    def test_dlt_metadata_excluded_from_data_columns(self) -> None:
        sql = generate_staging_sql(
            source_name="my_source",
            table_name="my_table",
            columns=self._basic_columns(),
        )
        assert "_dlt_id" not in sql

    def test_load_id_aliased(self) -> None:
        sql = generate_staging_sql(
            source_name="my_source",
            table_name="my_table",
            columns=self._basic_columns(),
        )
        assert "as load_id" in sql

    def test_snake_case_alias_applied(self) -> None:
        sql = generate_staging_sql(
            source_name="my_source",
            table_name="my_table",
            columns=self._basic_columns(),
        )
        assert "as commissioner_org_code" in sql

    def test_date_column_rendered(self) -> None:
        sql = generate_staging_sql(
            source_name="my_source",
            table_name="my_table",
            columns=self._basic_columns(),
        )
        assert '"Period"' in sql
        assert "as period" in sql

    def test_ambiguous_column_flagged_with_todo(self) -> None:
        cols = [
            ColumnInfo(name="Metadata", data_type="JSON", is_nullable=True),
        ]
        sql = generate_staging_sql(
            source_name="s",
            table_name="t",
            columns=cols,
        )
        assert "-- TODO: verify type" in sql

    def test_no_todo_for_clean_columns(self) -> None:
        cols = [
            ColumnInfo(name="OrgCode", data_type="VARCHAR", is_nullable=True),
        ]
        sql = generate_staging_sql(
            source_name="s",
            table_name="t",
            columns=cols,
        )
        select_body = sql.split("select", 1)[1]
        assert "TODO" not in select_body

    def test_last_select_line_has_no_trailing_comma(self) -> None:
        sql = generate_staging_sql(
            source_name="my_source",
            table_name="my_table",
            columns=self._basic_columns(),
        )
        lines = sql.splitlines()
        from_line_idx = next(i for i, l in enumerate(lines) if l.startswith("from "))
        last_select_line = lines[from_line_idx - 1].rstrip()
        assert not last_select_line.endswith(","), f"Trailing comma on: {last_select_line!r}"

    def test_custom_silver_schema_env_var(self) -> None:
        sql = generate_staging_sql(
            source_name="s",
            table_name="t",
            columns=[ColumnInfo(name="id", data_type="INTEGER")],
            silver_schema_env_var="MY_SILVER",
            silver_schema_default="my_silver",
        )
        assert "env_var('MY_SILVER', 'my_silver')" in sql

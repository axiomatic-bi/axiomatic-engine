"""
Unit tests for axiomatic_engine.cli.staging_generator.

Tests cover:
- to_snake_case: naming edge cases
- _resolve_cast: type mapping and ambiguity flagging
- generate_staging_sql: end-to-end SQL output contract
"""
from __future__ import annotations

import pytest

from axiomatic_engine.cli.staging_generator import (
    _resolve_cast,
    generate_staging_sql,
    to_snake_case,
)
from axiomatic_engine.contracts.warehouse import ColumnInfo


class TestToSnakeCase:
    def test_simple_space_separated(self) -> None:
        assert to_snake_case("Commissioner Org Code") == "commissioner_org_code"

    def test_leading_digit_moved_to_end(self) -> None:
        result = to_snake_case("0 To 1 Weeks SUM 1")
        assert not result[0].isdigit(), f"Should not start with digit: {result}"

    def test_already_snake(self) -> None:
        assert to_snake_case("already_snake") == "already_snake"

    def test_dlt_prefix_preserved(self) -> None:
        assert to_snake_case("_dlt_load_id") == "_dlt_load_id"

    def test_multiple_underscores_collapsed(self) -> None:
        result = to_snake_case("col__name  test")
        assert "__" not in result

    def test_special_chars_stripped(self) -> None:
        result = to_snake_case("Col (Units) %")
        assert "(" not in result
        assert "%" not in result

    def test_mixed_case(self) -> None:
        assert to_snake_case("PeriodDate") == "perioddate"

    def test_all_digits(self) -> None:
        result = to_snake_case("123")
        assert result and not result[0].isdigit()

    def test_empty_after_strip(self) -> None:
        result = to_snake_case("---")
        assert result != ""


